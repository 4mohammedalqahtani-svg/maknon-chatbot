/** تنسيق مستند واحد داخل التعليمات */
function formatDoc(d, i) {
  const where = d.path ? ` — المسار: ${d.path}` : '';
  return `--- [مستند ${i + 1}] ${d.name}${where} ---\n${d.text}`;
}

/**
 * الجزء الثابت من التعليمات (قابل للتخزين المؤقت لدى OpenAI).
 * في وضع "full" يحتوي كل نصوص المستندات.
 * في وضع "embed" يحتوي القواعد فقط، والمقاطع المختارة تُرسَل في رسالة منفصلة.
 */
export function buildStaticSystemPrompt() {
  if (knowledge.mode === 'full') {
    if (!knowledge.docs.length) {
      return `${RULES}\n\n(لا توجد مستندات محمّلة حاليًا. اعتذر لكل سؤال بالجملة المذكورة في القاعدة رقم 2.)`;
    }
    const body = knowledge.docs.map(formatDoc).join('\n\n');
    return `${RULES}\n\n${body}\n\n# انتهت المستندات\nتذكّر: كل ما سبق هو مصدرك الوحيد.`;
  }

  // وضع embeddings: المقاطع المختارة تُضاف لاحقًا لكل سؤال
  return `${RULES}\n\nستصلك في رسالة تالية المقاطع الأكثر صلة بسؤال المستخدم من مستندات الجمعية. اعتمد عليها وحدها.`;
}

/** يبني رسالة السياق في وضع embeddings */
export function buildContextMessage(passages) {
  if (!passages.length) {
    return 'لم يُعثر على أي مقطع ذي صلة في مستندات الجمعية. استخدم جملة الاعتذار المذكورة في القاعدة رقم 2.';
  }
  const body = passages
    .map((p, i) => `--- [مقطع ${i + 1}] من ملف: ${p.title} ---\n${p.text}`)
    .join('\n\n');
  return `# المقاطع ذات الصلة من مستندات الجمعية\n\n${body}\n\n# انتهت المقاطع\nتذكّر: هذه هي مصدرك الوحيد لهذه الإجابة.`;
}

